-- 009 — Riwayat backup database (PostgreSQL).
-- Tabel ini juga dibuat otomatis oleh server/lib/sistem.ts; migrasi ini untuk
-- instalasi baru/audit agar riwayat backup tidak bergantung pada backup pertama.
CREATE TABLE IF NOT EXISTS system_backups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL UNIQUE,
  ukuran BIGINT NOT NULL DEFAULT 0,
  tipe TEXT NOT NULL DEFAULT 'manual',
  status TEXT NOT NULL DEFAULT 'sukses',
  galat TEXT,
  dibuat_oleh BIGINT REFERENCES users(id) ON DELETE SET NULL,
  dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_system_backups_waktu ON system_backups (dibuat_pada DESC);
CREATE INDEX IF NOT EXISTS idx_system_backups_status ON system_backups (status, dibuat_pada DESC);
