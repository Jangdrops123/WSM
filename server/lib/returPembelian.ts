// ============================================================================
// RETUR PEMBELIAN — mengembalikan barang yang sudah diterima ke pemasok.
//
// Retur penjualan punya tabel sendiri (sale_returns). Untuk pembelian, tabel
// retur dibuat di sini secara idempoten (CREATE TABLE IF NOT EXISTS) agar
// tidak bergantung pada langkah migrasi manual: satu dokumen retur menyimpan
// header (nomor, tanggal, alasan, nilai) + baris item yang dikembalikan.
//
// Efek satu retur (semua dalam SATU transaksi pemanggil):
//   1. stok KELUAR dari gudang dokumen pembelian (kartu stok tipe 'retur');
//   2. hutang pemasok berkurang sebesar nilai retur (bila sudah ada hutang);
//      bila tidak ada hutang, uang kembali masuk ke kas tunai (refund);
//   3. audit log + nomor dokumen 'RTP' otomatis.
//
// Qty retur dibatasi qty yang dibeli − qty yang sudah diretur sebelumnya.
// ============================================================================
import { all, get, run } from '../db.pg.ts';
import { nomorOtomatis } from './pengaturanBaru.ts';
import { tolak } from './http.ts';
import { ubahStok } from './stok.ts';
import { catatAudit } from './audit.ts';
import { akunKasMetode, catatMutasiKas } from './dasarKas.ts';

let tabelSiap = false;

/** Buat tabel retur pembelian bila belum ada (idempoten, sekali per proses). */
export async function pastikanTabelRetur(): Promise<void> {
  if (tabelSiap) return;
  // `purchase_id` boleh NULL: retur bisa dibuat langsung dari PO (penerimaan
  // fisik) tanpa dokumen faktur, dan `po_id` menyimpan tautan PO-nya.
  await run(`
    CREATE TABLE IF NOT EXISTS purchase_returns (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      no_dokumen TEXT NOT NULL UNIQUE,
      purchase_id BIGINT,
      po_id BIGINT,
      tanggal TIMESTAMPTZ NOT NULL DEFAULT now(),
      alasan TEXT,
      total NUMERIC(19,4) NOT NULL DEFAULT 0,
      status TEXT NOT NULL DEFAULT 'disahkan',
      dibuat_oleh BIGINT,
      dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);
  // Migrasi idempoten untuk tabel lama (retur faktur): tambah po_id dan lepas
  // NOT NULL purchase_id agar retur berbasis PO bisa disimpan.
  await run(`ALTER TABLE purchase_returns ADD COLUMN IF NOT EXISTS po_id BIGINT`);
  await run(`ALTER TABLE purchase_returns ALTER COLUMN purchase_id DROP NOT NULL`);
  await run(`CREATE INDEX IF NOT EXISTS idx_purchase_returns_po ON purchase_returns (po_id)`);
  await run(`
    CREATE TABLE IF NOT EXISTS purchase_return_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      return_id BIGINT NOT NULL,
      product_id BIGINT NOT NULL,
      nama_produk TEXT,
      sku TEXT,
      qty NUMERIC(19,4) NOT NULL DEFAULT 0,
      harga NUMERIC(19,4) NOT NULL DEFAULT 0
    )`);
  await run(`CREATE INDEX IF NOT EXISTS idx_purchase_returns_purchase ON purchase_returns (purchase_id)`);
  await run(`CREATE INDEX IF NOT EXISTS idx_purchase_return_items_return ON purchase_return_items (return_id)`);
  tabelSiap = true;
}

export interface ItemReturMasuk {
  product_id: number;
  qty: number;
}

export interface HasilReturPembelian {
  id: number;
  no_dokumen: string;
  total: number;
  items: { product_id: number; nama: string; sku: string; qty: number; harga: number }[];
}

/** Qty (satuan dasar) yang sudah pernah diretur untuk satu dokumen pembelian. */
async function qtySudahRetur(purchaseId: number): Promise<Map<number, number>> {
  const rows = await all<{ product_id: number; qty: number }>(
    `SELECT ri.product_id, COALESCE(SUM(ri.qty), 0) AS qty
       FROM purchase_return_items ri
       JOIN purchase_returns r ON r.id = ri.return_id
      WHERE r.purchase_id = ? AND r.status = 'disahkan'
      GROUP BY ri.product_id`,
    purchaseId,
  );
  const peta = new Map(rows.map((r) => [Number(r.product_id), Number(r.qty)]));
  // Retur yang dicatat lewat modul PO (tanpa faktur / po_id) untuk nomor PO
  // yang sama ikut mengurangi sisa agar tidak terjadi retur ganda.
  const p = await get<{ no_po: string | null }>(`SELECT no_po FROM purchases WHERE id = ?`, purchaseId);
  if (p?.no_po) {
    const rowsPo = await all<{ product_id: number; qty: number }>(
      `SELECT ri.product_id, COALESCE(SUM(ri.qty), 0) AS qty
         FROM purchase_return_items ri
         JOIN purchase_returns r ON r.id = ri.return_id
         JOIN purchase_orders po ON po.id = r.po_id
        WHERE r.status = 'disahkan' AND po.no_po = ?
          AND (r.purchase_id IS NULL OR r.purchase_id <> ?)
        GROUP BY ri.product_id`,
      p.no_po,
      purchaseId,
    );
    for (const r of rowsPo) {
      const pid = Number(r.product_id);
      peta.set(pid, (peta.get(pid) ?? 0) + Number(r.qty));
    }
  }
  return peta;
}

/** Satu baris barang yang masih bisa diretur dari sebuah PO. */
export interface KetersediaanReturPo {
  product_id: number;
  nama: string;
  sku: string;
  harga: number;
  /** Total qty fisik yang pernah diterima (po_receipt_items). */
  qty_diterima: number;
  /** Qty yang sudah diretur sebelumnya. */
  sudah_retur: number;
  /** Sisa qty yang boleh diretur sekarang. */
  qty_maks: number;
}

/** Qty yang sudah diretur untuk sebuah PO (po_id maupun faktur bernomor PO sama). */
async function qtySudahReturPo(poId: number, noPo: string): Promise<Map<number, number>> {
  const rows = await all<{ product_id: number; qty: number }>(
    `SELECT ri.product_id, COALESCE(SUM(ri.qty), 0) AS qty
       FROM purchase_return_items ri
       JOIN purchase_returns r ON r.id = ri.return_id
       LEFT JOIN purchase_orders po ON po.id = r.po_id
       LEFT JOIN purchases p ON p.id = r.purchase_id
      WHERE r.status = 'disahkan' AND (r.po_id = ? OR p.no_po = ?)
      GROUP BY ri.product_id`,
    poId,
    noPo,
  );
  return new Map(rows.map((r) => [Number(r.product_id), Number(r.qty)]));
}

/**
 * Ketersediaan retur sebuah PO DARI PENERIMAAN FISIK (po_receipts /
 * po_receipt_items) — bukan dari flag faktur. Inilah sumber kebenaran
 * "barang sudah diterima": PO berstatus sebagian/selesai/lebih dengan
 * akumulasi qty_datang > 0 selalu bisa diretur walau belum difakturkan.
 */
export async function ketersediaanReturPo(poId: number): Promise<KetersediaanReturPo[]> {
  await pastikanTabelRetur();
  const po = await get<{ id: number; no_po: string }>(`SELECT id, no_po FROM purchase_orders WHERE id = ?`, poId);
  if (!po) throw tolak(404, 'PO tidak ditemukan.');
  const diterima = await all<{ product_id: number; qty: number; nama: string; sku: string; harga: string | number }>(
    `SELECT ri.product_id,
            COALESCE(SUM(ri.qty_datang), 0) AS qty,
            MAX(pr.nama) AS nama,
            MAX(pr.sku) AS sku,
            MAX(COALESCE(poi.harga_beli, pr.harga_beli, 0)) AS harga
       FROM po_receipt_items ri
       JOIN po_receipts r ON r.id = ri.receipt_id
       JOIN products pr ON pr.id = ri.product_id
       LEFT JOIN purchase_order_items poi ON poi.po_id = r.po_id AND poi.product_id = ri.product_id
      WHERE r.po_id = ?
      GROUP BY ri.product_id
      ORDER BY MAX(pr.nama)`,
    poId,
  );
  const sudah = await qtySudahReturPo(po.id, po.no_po);
  const keluar: KetersediaanReturPo[] = [];
  for (const d of diterima) {
    const qtyDiterima = Number(d.qty) || 0;
    if (qtyDiterima <= 0) continue;
    const pid = Number(d.product_id);
    const sudahRetur = Number(sudah.get(pid) ?? 0);
    keluar.push({
      product_id: pid,
      nama: String(d.nama ?? ''),
      sku: String(d.sku ?? ''),
      harga: Number(d.harga) || 0,
      qty_diterima: qtyDiterima,
      sudah_retur: sudahRetur,
      qty_maks: Math.max(0, qtyDiterima - sudahRetur),
    });
  }
  return keluar;
}

/**
 * Efek keuangan retur: hutang pemasok berkurang; bila tidak ada hutang
 * tersisa, uang masuk kembali ke kas (refund). Dipakai jalur retur faktur
 * maupun retur PO yang sudah difakturkan.
 */
async function koreksiKeuanganRetur(
  purchaseId: number,
  total: number,
  noDokumenBeli: string,
  noRetur: string,
  returId: number,
  userId: number | null,
): Promise<void> {
  const hutang = await get<{ id: number; total: number; terbayar: number }>(
    `SELECT id, total, terbayar FROM payables WHERE purchase_id = ?`,
    purchaseId,
  );
  let sisaNilai = total;
  if (hutang) {
    const sisaHutang = Math.max(0, Number(hutang.total) - Number(hutang.terbayar));
    const dipotong = Math.min(sisaHutang, sisaNilai);
    if (dipotong > 0) {
      await run(`UPDATE payables SET total = ? WHERE id = ?`, Number(hutang.total) - dipotong, hutang.id);
      sisaNilai -= dipotong;
    }
  }
  if (sisaNilai > 0) {
    const akunKas = await akunKasMetode('tunai');
    if (akunKas) {
      await catatMutasiKas({
        tipe: 'masuk',
        akunId: akunKas.id,
        jumlah: sisaNilai,
        keterangan: `Refund retur pembelian ${noDokumenBeli} → ${noRetur}`,
        sumberTipe: 'retur_pembelian',
        sumberId: returId,
        dibuatOleh: userId,
      });
    }
  }
}

/**
 * Proses retur pembelian. WAJIB dipanggil di dalam withTransaction() milik
 * pemanggil (stok + hutang + kas harus atomik).
 */
export async function returPembelian(
  purchaseId: number,
  minta: ItemReturMasuk[],
  alasan: string | null,
  userId: number | null,
): Promise<HasilReturPembelian> {
  await pastikanTabelRetur();
  const p = await get<{ id: number; status: string; no_dokumen: string; warehouse_id: number; supplier_id: number }>(
    `SELECT id, status, no_dokumen, warehouse_id, supplier_id FROM purchases WHERE id = ?`,
    purchaseId,
  );
  if (!p) throw tolak(404, 'Dokumen pembelian tidak ditemukan.');
  if (p.status !== 'disahkan') {
    throw tolak(409, 'Retur pembelian hanya untuk dokumen yang sudah disahkan (stok sudah masuk).');
  }
  if (!Array.isArray(minta) || minta.length === 0) throw tolak(400, 'Pilih item yang diretur.');

  const sudah = await qtySudahRetur(purchaseId);
  const rincian: { product_id: number; nama: string; sku: string; qty: number; harga: number }[] = [];
  let total = 0;

  for (const m of minta) {
    const qty = Number(m.qty);
    if (!Number.isFinite(qty) || qty <= 0) continue;
    const pid = Number(m.product_id);
    const dibeli = await get<{ qty: number; harga: number; nama_produk: string; sku: string }>(
      `SELECT COALESCE(SUM(qty), 0) AS qty, MAX(harga_beli) AS harga,
              MAX(nama_produk) AS nama_produk, MAX(sku) AS sku
         FROM purchase_items WHERE purchase_id = ? AND product_id = ?`,
      purchaseId,
      pid,
    );
    if (!dibeli || Number(dibeli.qty) <= 0) throw tolak(400, 'Item bukan bagian pembelian ini.');
    const sisa = Number(dibeli.qty) - Number(sudah.get(pid) ?? 0);
    if (qty > sisa + 1e-9) {
      throw tolak(409, `Qty retur melebihi sisa yang bisa diretur (${sisa}) untuk produk ${dibeli.sku}.`);
    }
    const harga = Number(dibeli.harga ?? 0);
    total += qty * harga;
    rincian.push({ product_id: pid, nama: dibeli.nama_produk, sku: dibeli.sku, qty, harga });
  }
  if (rincian.length === 0) throw tolak(400, 'Tidak ada item valid untuk diretur.');

  const noRetur = await nomorOtomatis('retur_pembelian');
  const returId = Number(
    await (await run(
      `INSERT INTO purchase_returns (no_dokumen, purchase_id, tanggal, alasan, total, status, dibuat_oleh)
       VALUES (?, ?, ?, ?, ?, 'disahkan', ?)`,
      noRetur,
      purchaseId,
      new Date().toISOString(),
      alasan,
      total,
      userId,
    )).lastInsertRowid,
  );

  for (const it of rincian) {
    await run(
      `INSERT INTO purchase_return_items (return_id, product_id, nama_produk, sku, qty, harga)
       VALUES (?, ?, ?, ?, ?, ?)`,
      returId,
      it.product_id,
      it.nama,
      it.sku,
      it.qty,
      it.harga,
    );
    // Stok keluar dari gudang dokumen pembelian + kartu stok (tipe 'retur').
    await ubahStok({
      productId: it.product_id,
      warehouseId: p.warehouse_id,
      keluar: it.qty,
      tipeDokumen: 'retur',
      dokumenId: returId,
      userId,
    });
  }

  await koreksiKeuanganRetur(purchaseId, total, p.no_dokumen, noRetur, returId, userId);

  await catatAudit({
    userId,
    aksi: 'tambah',
    tabel: 'purchase_returns',
    recordId: returId,
    sesudah: { no_dokumen: noRetur, purchase_id: purchaseId, total, items: rincian.length },
    alasan: alasan ?? undefined,
  });

  return { id: returId, no_dokumen: noRetur, total, items: rincian };
}

/**
 * Retur atas PO berdasarkan PENERIMAAN FISIK (po_receipts / po_receipt_items).
 *
 * Dipakai modul PO: PO dengan status "terkirim", "sebagian", "selesai"
 * (atau "lebih") dan akumulasi qty_datang > 0 bisa diretur walau BELUM ada
 * dokumen `purchases`/faktur — dulu jalur ini selalu 409 karena hanya mencari
 * `purchases.status = 'disahkan'`.
 *
 * Bila PO sudah difakturkan (ada purchases disahkan bernomor PO sama), efek
 * hutang/kas ikut dikoreksi; tanpa faktur, retur hanya mengeluarkan stok
 * karena barang belum menimbulkan hutang.
 *
 * WAJIB dipanggil di dalam withTransaction() milik pemanggil.
 */
export async function returPembelianPo(
  poId: number,
  minta: ItemReturMasuk[],
  alasan: string | null,
  userId: number | null,
): Promise<HasilReturPembelian> {
  await pastikanTabelRetur();
  const po = await get<{ id: number; no_po: string; warehouse_id: number }>(
    `SELECT id, no_po, warehouse_id FROM purchase_orders WHERE id = ?`,
    poId,
  );
  if (!po) throw tolak(404, 'PO tidak ditemukan.');
  if (!Array.isArray(minta) || minta.length === 0) throw tolak(400, 'Pilih item yang diretur.');

  const tersedia = await ketersediaanReturPo(po.id);
  const peta = new Map(tersedia.map((t) => [t.product_id, t]));
  // Tidak ada penerimaan fisik sama sekali → tolak dengan pesan yang jujur
  // (bukan lagi menyalahkan "faktur belum disahkan").
  if (tersedia.length === 0) {
    throw tolak(
      409,
      'Belum ada penerimaan fisik (Barang Datang) untuk PO ini — catat kedatangan barang dulu, retur baru bisa dilakukan setelah ada qty yang diterima.',
    );
  }
  if (tersedia.every((t) => t.qty_maks <= 0)) {
    throw tolak(409, 'Semua barang pada PO ini sudah pernah diretur — tidak ada qty tersisa untuk diretur.');
  }

  const rincian: { product_id: number; nama: string; sku: string; qty: number; harga: number }[] = [];
  let total = 0;
  for (const m of minta) {
    const qty = Number(m.qty);
    if (!Number.isFinite(qty) || qty <= 0) continue;
    const t = peta.get(Number(m.product_id));
    if (!t) throw tolak(400, 'Item bukan bagian penerimaan PO ini.');
    if (qty > t.qty_maks + 1e-9) {
      throw tolak(
        409,
        `Qty retur melebihi sisa yang bisa diretur (${t.qty_maks}) untuk produk ${t.sku || t.nama}. Sisa = qty diterima ${t.qty_diterima} − sudah diretur ${t.sudah_retur}.`,
      );
    }
    total += qty * t.harga;
    rincian.push({ product_id: t.product_id, nama: t.nama, sku: t.sku, qty, harga: t.harga });
  }
  if (rincian.length === 0) throw tolak(400, 'Tidak ada item valid untuk diretur.');

  const noRetur = await nomorOtomatis('retur_pembelian');
  const returId = Number(
    await (await run(
      `INSERT INTO purchase_returns (no_dokumen, purchase_id, po_id, tanggal, alasan, total, status, dibuat_oleh)
       VALUES (?, NULL, ?, ?, ?, ?, 'disahkan', ?)`,
      noRetur,
      po.id,
      new Date().toISOString(),
      alasan,
      total,
      userId,
    )).lastInsertRowid,
  );

  for (const it of rincian) {
    await run(
      `INSERT INTO purchase_return_items (return_id, product_id, nama_produk, sku, qty, harga)
       VALUES (?, ?, ?, ?, ?, ?)`,
      returId,
      it.product_id,
      it.nama,
      it.sku,
      it.qty,
      it.harga,
    );
    // Stok keluar dari gudang PO + kartu stok (tipe 'retur').
    await ubahStok({
      productId: it.product_id,
      warehouseId: po.warehouse_id,
      keluar: it.qty,
      tipeDokumen: 'retur',
      dokumenId: returId,
      userId,
    });
  }

  const faktur = await get<{ id: number; no_dokumen: string }>(
    `SELECT id, no_dokumen FROM purchases
      WHERE no_po = ? AND status = 'disahkan' ORDER BY id DESC LIMIT 1`,
    po.no_po,
  );
  if (faktur) await koreksiKeuanganRetur(faktur.id, total, faktur.no_dokumen, noRetur, returId, userId);

  await catatAudit({
    userId,
    aksi: 'tambah',
    tabel: 'purchase_returns',
    recordId: returId,
    sesudah: { no_dokumen: noRetur, po_id: po.id, no_po: po.no_po, total, items: rincian.length },
    alasan: alasan ?? undefined,
  });

  return { id: returId, no_dokumen: noRetur, total, items: rincian };
}

/** Riwayat retur satu dokumen pembelian (untuk modal Lihat). */
export async function daftarReturPembelian(purchaseId: number): Promise<Record<string, unknown>[]> {
  await pastikanTabelRetur();
  return await all<Record<string, unknown>>(
    `SELECT id, no_dokumen, tanggal, alasan, total, status
       FROM purchase_returns WHERE purchase_id = ? ORDER BY id DESC`,
    purchaseId,
  );
}
