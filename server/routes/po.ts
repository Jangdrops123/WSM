/** Validasi tanggal tenggat (YYYY-MM-DD) → string tanggal atau null. */
export function tenggatValid(v: unknown): string | null {
  const s = String(v ?? '').trim();
  if (!s) return null;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) throw tolak(400, 'Tanggal tenggat tidak valid (format: YYYY-MM-DD).');
  const d = new Date(`${s}T12:00:00`);
  if (Number.isNaN(d.getTime())) throw tolak(400, 'Tanggal tenggat tidak valid.');
  return s;
}

/** Pastikan tabel PO ada (idempoten — menutup celah bila migrasi psql belum dijalankan). */
let skemaSiap = false;
async function pastikanSkema(): Promise<void> {
  if (skemaSiap) return;
  await run(`CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_po TEXT NOT NULL UNIQUE, tanggal TIMESTAMPTZ NOT NULL DEFAULT now(),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
    catatan TEXT, tenggat TIMESTAMPTZ, status TEXT NOT NULL DEFAULT 'draft',
    total_pcs BIGINT NOT NULL DEFAULT 0, total_harga NUMERIC(19,4) NOT NULL DEFAULT 0,
    dikirim_pada TIMESTAMPTZ, dikirim_tujuan TEXT, ditutup_pada TIMESTAMPTZ,
    dibuat_oleh BIGINT REFERENCES users(id),
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now(), diubah_pada TIMESTAMPTZ)`);
  await run(`CREATE TABLE IF NOT EXISTS purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    qty_pesan BIGINT NOT NULL CHECK (qty_pesan > 0),
    harga_beli NUMERIC(19,4) NOT NULL DEFAULT 0, satuan TEXT NOT NULL DEFAULT 'pcs',
    catatan TEXT,
    UNIQUE (po_id, product_id))`);
  await run(`CREATE TABLE IF NOT EXISTS po_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id BIGINT REFERENCES purchase_orders(id) ON DELETE SET NULL,
    tanggal TIMESTAMPTZ NOT NULL DEFAULT now(), no_surat_jalan TEXT, catatan TEXT,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
    dibuat_oleh BIGINT REFERENCES users(id), dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now())`);
  await run(`CREATE TABLE IF NOT EXISTS po_receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES po_receipts(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    qty_datang BIGINT NOT NULL CHECK (qty_datang > 0),
    catatan TEXT)`);
  // Kolom keterangan per barang (instalasi lama yang tabelnya sudah ada).
  await run(`ALTER TABLE purchase_order_items ADD COLUMN IF NOT EXISTS catatan TEXT`);
  await run(`ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS tenggat TIMESTAMPTZ`);
  await run(`ALTER TABLE po_receipt_items ADD COLUMN IF NOT EXISTS catatan TEXT`);
  // Penanda barang luar PO (tidak tercantum di purchase_order_items).
  await run(`ALTER TABLE po_receipt_items ADD COLUMN IF NOT EXISTS is_unplanned BOOLEAN NOT NULL DEFAULT false`);
  // PPN opsional saat pembuatan PO (bawaan: tidak aktif / 0%).
  await run(`ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS is_tax_enabled BOOLEAN NOT NULL DEFAULT false`);
  await run(`ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS tax_rate NUMERIC(5,2) NOT NULL DEFAULT 11`);
  // Penanda PO ditutup manual oleh pengguna (Selesaikan Manual). Bedanya dengan
  // selesai otomatis: penutupan manual mengabaikan sisa yang belum datang.
  await run(`ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS is_manually_closed BOOLEAN NOT NULL DEFAULT false`);
  // PO susulan menunjuk PO induknya (opsional). Nomor PO tetap baru & berurutan.
  await run(`ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS parent_po_id BIGINT REFERENCES purchase_orders(id)`);
  await run(`INSERT INTO settings (kunci, nilai, keterangan) VALUES ('isi_per_kodi', '20', 'Jumlah pcs dalam 1 kodi untuk modul Purchase')
    ON CONFLICT(kunci) DO NOTHING`);
  await run(`INSERT INTO settings (kunci, nilai, keterangan) VALUES ('enable_kodi_conversion', 'true', 'Tampilkan konversi kodi di modul Purchase (true/false)')
    ON CONFLICT(kunci) DO NOTHING`);
  skemaSiap = true;
}

/** Toggle konversi kodi di Purchase (bawaan aktif bila belum diatur). */
export async function kodiAktif(): Promise<boolean> {
  try {
    const s = await getSettings();
    const v = String(s['enable_kodi_conversion'] ?? 'true').toLowerCase();
    return v !== 'false' && v !== '0';
  } catch {
    return true;
  }
}

/** Isi per kodi dari Pengaturan (bawaan 20). */
export async function isiPerKodi(): Promise<number> {
  try {
    const s = await getSettings();
    const n = Number.parseInt(String(s['isi_per_kodi'] ?? '20'), 10);
    return Number.isFinite(n) && n > 0 ? n : 20;
  } catch {
    return 20;
  }
}

