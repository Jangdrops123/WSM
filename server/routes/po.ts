export const STATUS_PO = ['draft', 'terkirim', 'sebagian', 'selesai', 'selesai_kurang', 'lebih', 'kadaluwarsa', 'batal'] as const;
export type StatusPo = (typeof STATUS_PO)[number];

/** Pecah param `status` (boleh koma: "terkirim,sebagian") jadi daftar status valid. */
export function saringStatus(v: unknown): string[] {
  return String(v ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter((s) => (STATUS_PO as readonly string[]).includes(s));
}

